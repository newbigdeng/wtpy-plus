import { test, expect } from '@playwright/test'

import {fixture} from './fixtures/console.js'

test('login, live-log preference, group switch and WebSocket event routing',async({page})=>{
  const f=await fixture(page)
  const append=page.getByRole('checkbox',{name:'实时追加'})
  await expect(append).toBeChecked()
  f.send({type:'gplog',groupid:'acceptance01',tag:'INFO',time:Date.now(),message:'first-real-time-event'})
  await expect(page.locator('textarea[readonly]').first()).toHaveValue(/first-real-time-event/)
  await page.getByText('实时追加',{exact:true}).click()
  f.send({type:'gplog',groupid:'acceptance01',tag:'INFO',time:Date.now(),message:'must-stay-hidden'})
  await expect(page.locator('textarea[readonly]').first()).not.toHaveValue(/must-stay-hidden/)
  await page.getByRole('button',{name:'验收组合二',exact:true}).click()
  await expect(append).toBeChecked()
  await page.getByRole('button',{name:'验收组合一',exact:true}).click()
  await expect(append).not.toBeChecked()
  expect(await page.evaluate(()=>localStorage.getItem('wtpy.monitor.logAuto.acceptance01'))).toBe('false')
  await expect(page.getByRole('button',{name:/停止$/})).toBeHidden()
  expect(f.errors).toEqual([])
})

test('CodeMirror 6 read-only, edit, save and cancel retain the existing JSON file API',async({page})=>{
  const f=await fixture(page)
  await page.getByRole('button',{name:'配置',exact:true}).click()
  await page.getByRole('tab',{name:'配置文件',exact:true}).click()
  await page.getByRole('treeitem',{name:'root'}).locator('.el-tree-node__expand-icon').first().click()
  await page.getByText('config.json',{exact:true}).click()
  const editor=page.locator('.cm-content:visible')
  await expect(editor).toHaveAttribute('contenteditable','false')
  await expect(editor).toHaveText('{"enabled":true}')
  await page.getByRole('button',{name:/修改$/}).click()
  await expect(editor).toHaveAttribute('contenteditable','true')
  await editor.fill('{"enabled":false}')
  await page.getByRole('button',{name:/提交$/}).click()
  await expect.poll(()=>f.calls.filter(call=>call.path==='/mgr/cmtgrpfile').length).toBe(1)
  expect(f.calls.find(call=>call.path==='/mgr/cmtgrpfile').data.content).toBe('{"enabled":false}')
  await page.getByRole('button',{name:/修改$/}).click()
  await editor.fill('discard me')
  await page.getByRole('button',{name:/取消$/}).click()
  await page.getByRole('button',{name:'确定',exact:true}).click()
  await expect(editor).toHaveText('{"enabled":false}')
  expect(f.errors).toEqual([])
})

